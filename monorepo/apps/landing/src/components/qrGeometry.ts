import { QR_BITS, QR_SIZE } from './qrMatrix';
import { mulberry32 } from './rand';

/* The QR's geometry, deliberately kept OUT of a 'use client' module.

   Both the hero (a client component, because it tracks the pointer) and the
   section figures (server-rendered) draw from these, and a client module's
   exports cannot be called from the server. So the maths lives here and the
   components import it, which is also what guarantees the figures below the
   hero run the same ramp as the code itself rather than a copy of it.

   THE CODE IS REAL AND SCANNABLE. It is the matrix in qrMatrix.ts, generated by
   scripts/gen-qr.mjs, and it is drawn whole: every module present, every module
   at full opacity, every module on the pitch.

   That is a change from the decorative version, and it forced the dissolve to
   move. A dissolving matrix and a scannable one are in direct conflict: culling
   data modules spends the error-correction budget, and a module sitting at a
   mid-ramp opacity is neither dark nor light to a scanner, which is worse than
   one that is simply absent. So the code no longer comes apart. Instead it
   SHEDS: past the quiet zone, a trail of modules carries the same dissolveAt /
   rampAt / RAMP the section figures run on. The motif survives untouched and
   the payload is never at risk. */

const N = QR_SIZE; // modules per side of the code itself
export const M = 12; // px per module

/* A QR needs a light margin to be found at all. Four modules is the spec
   minimum, and it doubles as the gap that keeps the trail from being read as
   part of the code. */
export const QUIET = 4;
const TRAIL = 6; // columns of shed modules beyond the quiet zone

export const MATRIX_W = N * M; // the scannable part, for sizing the link target
export const QR_W = (N + QUIET + TRAIL) * M;
export const QR_H = N * M;

const FINDERS = [
  [0, 0],
  [N - 7, 0],
  [0, N - 7],
] as const;

/* The filled cells of a finder: the 7x7 outer ring plus the 3x3 core. Exported
   because the Security figure draws one on its own, and because the hero tints
   these three corners terracotta. The mark a scanner orients against is that
   section's whole argument, and it should be the same geometry the code itself
   is built from. */
export const isFinderCell = (x: number, y: number) =>
  FINDERS.some(([fx, fy]) => {
    const dx = x - fx;
    const dy = y - fy;
    if (dx < 0 || dx > 6 || dy < 0 || dy > 6) return false;
    return dx === 0 || dx === 6 || dy === 0 || dy === 6 || (dx >= 2 && dx <= 4 && dy >= 2 && dy <= 4);
  });

/* Dissolve strength: 0 until 4/7 of the way across, ramping to 1 at the right
   edge. The section figures run this over their own width; the hero's own code
   no longer uses it, because the code no longer dissolves. */
export const dissolveAt = (x: number, cols: number) =>
  Math.max(0, Math.min(1, (x - cols * (12 / 21)) / (cols * (8 / 21))));

/* Quantized opacity decay, the single most load-bearing constant on this page.
   A clean five-step ramp reads as resonance; the per-module random fade it
   replaced read as noise. Never interpolate it: the banding IS the effect. */
export const RAMP = [1, 0.65, 0.5, 0.4, 0.3] as const;
export const rampAt = (t: number) => RAMP[Math.min(RAMP.length - 1, Math.round(t * 4))];

// d/dx/dy drive the entrance: delay in ms, and the offset each module flies in
// from. Nothing here perturbs the resting position; x/y are always on-pitch.
export type Px = { x: number; y: number; o: number; terra: boolean; d: number; dx: number; dy: number };

const COLS = N + QUIET + TRAIL;

/* Split, not one list, and the split is load-bearing.

   The particle field used to rasterise the whole code and then HIDE the SVG,
   so on any WebGL machine the hero was 40k jittered sprites: beautiful, and
   impossible to scan, on exactly the desktop screen someone would point a
   phone at. Now the code is always the crisp SVG and the particles render the
   TRAIL. The shed modules are the part that should shatter and fly anyway, and
   the currency morph reads better on them than on the payment code itself. */
function qrPixels(): { matrix: Px[]; trail: Px[] } {
  const rnd = mulberry32(20260731);
  const matrix: Px[] = [];
  const trail: Px[] = [];

  // Delay tracks the column across the whole artwork, so the code assembles as
  // a left-to-right wave and the shed trail is the last thing to arrive.
  const enter = (x: number): Pick<Px, 'd' | 'dx' | 'dy'> => ({
    d: Math.round(300 + (x / COLS) * 600 + rnd() * 80),
    dx: Math.round(12 + rnd() * 24), // flies in from the right, with the flow
    dy: Math.round((rnd() - 0.5) * 16),
  });

  // The code. No randomness reaches position or opacity: this is a payload.
  for (let y = 0; y < N; y++) {
    for (let x = 0; x < N; x++) {
      if (QR_BITS[y * N + x] !== '1') continue;
      matrix.push({ x: x * M, y: y * M, o: 1, terra: isFinderCell(x, y), ...enter(x) });
    }
  }

  /* The trail, as a DECAY CHAIN rather than a fresh random draw per column.

     Drawing each column independently put modules at unrelated heights and read
     as confetti, which is the exact failure this system exists to avoid:
     repetition with clean decay reads as resonance, repetition with random
     position reads as noise. So the trail starts from the rows the code's own
     right edge occupies, and each column keeps a shrinking share of the rows
     the column before it held. The result streaks horizontally off the edge,
     and every module is a descendant of a real one. */
  let rows = new Set<number>();
  for (let y = 0; y < N; y++) {
    if (QR_BITS[y * N + (N - 1)] === '1' || QR_BITS[y * N + (N - 2)] === '1') rows.add(y);
  }

  for (let t = 0; t < TRAIL; t++) {
    const x = N + QUIET + t;
    const o = rampAt((t + 1) / TRAIL);
    // Keep most of the previous column at first, then let go faster.
    const keep = 0.78 - t * 0.1;
    rows = new Set([...rows].filter(() => rnd() < keep));
    for (const y of rows) {
      // Terracotta on the ramp's own step boundaries, so the accent lands on a
      // rhythm rather than at random.
      trail.push({ x: x * M, y: y * M, o, terra: (y + t) % 5 === 0, ...enter(x) });
    }
  }

  return { matrix, trail };
}

const { matrix, trail } = qrPixels();
export const MATRIX_PIXELS = matrix;
export const TRAIL_PIXELS = trail;
