/* Generates src/components/qrMatrix.ts — the real QR matrix behind the hero.
     yarn workspace @fpay/landing gen:qr

   One-shot, and the output is committed (same contract as brand/generate.mjs):
   nothing at build time depends on this, the client bundle carries only a
   bitstring, and the static export stays byte-deterministic.

   `qrcode` is not a declared dependency — it already resolves in the monorepo
   (apps/web pulls it in via qrcode.react) and this only ever runs by hand. */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import QRCode from 'qrcode';

// ECC-H: the highest error correction level, ~30% recoverable. The dissolve
// deliberately does not spend any of that budget (see qrGeometry), but the
// headroom is what lets this survive a phone camera at an angle, on a screen,
// through a reflection.
const URL_TARGET = 'https://frenspay.xyz/#flist';
const ECC = 'H';

const qr = QRCode.create(URL_TARGET, { errorCorrectionLevel: ECC });
const { size, data } = qr.modules;

const bits = Array.from(data, (b) => (b ? '1' : '0')).join('');
if (bits.length !== size * size) throw new Error(`expected ${size * size} modules, got ${bits.length}`);

const out = fileURLToPath(new URL('../src/components/qrMatrix.ts', import.meta.url));
writeFileSync(
  out,
  `// GENERATED by scripts/gen-qr.mjs. Do not edit by hand; re-run the script.
//
// A real, scannable QR for ${URL_TARGET} at error correction ${ECC}
// (version ${qr.version}, ${size}x${size}). Row-major, '1' = dark.
export const QR_URL = '${URL_TARGET}';
export const QR_ECC = '${ECC}';
export const QR_SIZE = ${size};
export const QR_BITS =
  '${bits}';
`,
);

console.log(`${out}\n  ${URL_TARGET}  ecc=${ECC}  v${qr.version}  ${size}x${size}  ${bits.length} modules`);
